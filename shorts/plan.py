def publish_time(day: date) -> str:
    """Когда публиковать Shorts (МСК): будни — 14:00, выходные — 12:00."""
    return "12:00" if day.weekday() >= 5 else "14:00"


def today(day: date) -> tuple[str, str] | None:
    return PLAN.get(day.isoformat())


def long_today(day: date) -> str | None:
    return LONG.get(day.isoformat())


def week(day: date, days: int = 7) -> list[tuple[date, tuple[str, str] | None, str | None]]:
    from datetime import timedelta
    return [(day + timedelta(n), today(day + timedelta(n)), long_today(day + timedelta(n))) for n in range(days)]


