STRESS = "́"
VOWELS = "АЕЁИОУЫЭЮЯ"

CUSTOM: dict[str, str] = {}  # свои замены, бот подгружает их из базы перед сборкой


def mark_stress(text: str) -> str:
    """«замОк» -> «замо́к», «ТЕнцинг» -> «Те́нцинг»: заглавная гласная внутри слова — ударная.

    Аббревиатуры (БАФТА) не трогаем: там за заглавной идёт заглавная.
    """
    def repl(m: re.Match[str]) -> str:
        before = text[m.start() - 1] if m.start() else ""
        after = text[m.end()] if m.end() < len(text) else ""
        stressed = before.islower() or (before.isalpha() and after.islower())
        return m.group(1).lower() + STRESS if stressed else m.group(1)

    return re.sub(rf"(?<=[а-яёА-ЯЁ])([{VOWELS}])", repl, text)


def _keep_case(original: str, spoken: str) -> str:
    """Слово с заглавной в начале предложения остаётся с заглавной."""
    if original[:1].isupper() and spoken[:1].islower():
        return spoken[:1].upper() + spoken[1:]
    return spoken


def dictionary_stressed() -> set[str]:
    """Слова со знаком ударения из словаря (встроенного и своего /say) — их ударение голос получает всегда, даже
    когда ударения от ИИ выключены (режим off): иначе «/say алая = АлАя» ничего не меняло."""
    out: set[str] = set()
    for value in list(DEFAULT.values()) + list(CUSTOM.values()):
        for word in re.findall(rf"[\w{STRESS}-]+", mark_stress(value)):
            if STRESS in word:
                out.add(word.lower())
    return out


def keep_dictionary_stress(text: str) -> str:
    """Убрать знаки ударения, кроме слов из словаря."""
    keep = dictionary_stressed()
    return re.sub(rf"[\w{STRESS}-]+", lambda m: m.group(0) if m.group(0).lower() in keep
                  else m.group(0).replace(STRESS, ""), text)


def parse_pairs(text: str) -> list[tuple[str, str]]:
    """/say: пары «слово = как читать». Каждая строка — пара; несколько пар в одной строке
    («Средиземье = средИземье Кольца власти = кОльца влАсти») делим так: в значении столько слов, сколько в
    слове слева (произношение того же слова), остальное — следующее слово. Раньше вся строка после первого «=»
    становилась одним значением, и голос зачитывал весь список."""
    pairs: list[tuple[str, str]] = []
    for line in text.splitlines():
        parts = [x.strip() for x in line.split("=")]
        if len(parts) < 2:
            continue
        key = parts[0]
        for seg in parts[1:-1]:
            words = seg.split()
            n = max(1, len(key.split()))
            value, nxt = " ".join(words[:n]), " ".join(words[n:])
            if key and value:
                pairs.append((key, value))
            key = nxt
        if key and parts[-1]:
            pairs.append((key, parts[-1]))
    return pairs


def repair(table: dict[str, str]) -> dict[str, str]:
    """Словарь, в который попало «слово = а Б = в» одной записью, — разложить на пары."""
    fixed: dict[str, str] = {}
    for key, value in table.items():
        if "=" in value:
            fixed.update(parse_pairs(f"{key} = {value}"))
        else:
            fixed[key] = value
    return fixed


def apply(text: str, extra: dict[str, str] | None = None) -> str:
    """Заменяет слова на их произношение; длинные варианты — первыми (HBO Max раньше HBO)."""
    table = {**DEFAULT, **CUSTOM, **(extra or {})}
    for word in sorted(table, key=len, reverse=True):
        # «IMAX-камера» тоже заменяем; слово, где ударение уже стоит («кобуре́»), второй раз не трогаем
        pattern = rf"(?<![\w-]){re.escape(word)}(?![\w{STRESS}])"
        # аббревиатуры (DC, IMAX) и «О Коннор» (не «о Конноре» — «про Коннора») — строго как в словаре
        flags = 0 if word.isupper() or word.startswith("О ") else re.IGNORECASE
        text = re.sub(pattern, lambda m, w=word: _keep_case(m.group(0), mark_stress(table[w])), text, flags=flags)
    return text


